CREATE TABLE IF NOT EXISTS ju_library (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    slug VARCHAR(160) NOT NULL UNIQUE,
    youtube VARCHAR(500) NULL DEFAULT NULL,
    audio VARCHAR(500) NULL DEFAULT NULL,
    video VARCHAR(500) NULL DEFAULT NULL,
    link VARCHAR(500) NULL DEFAULT NULL,
    image VARCHAR(500) NULL DEFAULT NULL,
    status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_ju_library_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
