CREATE TABLE IF NOT EXISTS ju_app_users (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    first_name VARCHAR(120) NOT NULL,
    last_name VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    profile_thumbnail VARCHAR(255) NULL,
    device_id VARCHAR(255) NULL,
    current_stage VARCHAR(120) NULL,
    birth_date DATE NULL,
    reduce_stress TINYINT(1) NOT NULL DEFAULT 0,
    sleep_better TINYINT(1) NOT NULL DEFAULT 0,
    build_heithy_habits TINYINT(1) NOT NULL DEFAULT 0,
    journal_throughts TINYINT(1) NOT NULL DEFAULT 0,
    find_professional_support TINYINT(1) NOT NULL DEFAULT 0,
    status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
    last_login_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
